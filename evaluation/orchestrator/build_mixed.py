def build():
    cases = []

    def add(group, query, routes, **kwargs):
        i = len(cases) + 1
        cases.append(
            dict(
                id=f"mix-{i:03}",
                group=group,
                query=query,
                scenario_id=772,
                history=[],
                disabled_agents=[],
                expected_mode="execute" if routes else "needs_clarification",
                expected_agents=routes,
                required_task_terms=[],
                split="holdout" if i % 5 == 0 else "development",
                answer_rubric=[RUBRICS[a] for a in routes]
                or [
                    "Объяснить недостающий контекст или предел возможностей; не выполнять неподдерживаемое действие, не выдавать частичный результат за полный."
                ],
            )
        )
        cases[-1].update(kwargs)

    def block(name, text):
        for line in text.strip().splitlines():
            agents, query = line.split("|", 1)
            add(name, query, agents.split(",") if agents else [])

    block("two_agents", TWO)
    block("three_agents", THREE)
    for prev, q, routes, terms in HISTORY:
        add(
            "complex_history",
            q,
            routes.split(","),
            history=[dict(role="user", content=prev)],
            required_task_terms=terms,
        )
    block("comparisons_and_data", DATA)
    block("limits_and_conflicts", BOUNDARIES)
    for q, scenario, disabled, routes in UNAVAILABLE:
        add(
            "missing_context", q, routes, scenario_id=scenario, disabled_agents=disabled
        )
    assert len(cases) == 100, len(cases)
