#!/usr/bin/env python3
"""Expand the expert gold set with additional paraphrases of the 202 base queries.

A paraphrase changes only the *wording* of the question; the expected answer,
entities, buffer parameter and reference GeoJSON are inherited unchanged from the
base record (same scenario_id). This grows evaluation coverage / robustness
without new manual expert annotation.

Paraphrases are generated by an Ollama model on the shared server and are
validated so the buffer distance and the core object nouns from the base
question are preserved (a paraphrase that drops "200 метров" or swaps the
entities would silently change the gold, so it is rejected and regenerated).

Output: an augmented CSV with the same columns as full_dataset.csv plus
`base_index` (provenance to the base expert row) and `variant` (0 = original).

Usage:
    python benchmarks/harness/expand_dataset.py \
        --ollama-host http://a.dgx:11434 --model gpt-oss:20b \
        --n-paraphrases 10 --out benchmarks/data/gold/expanded.csv
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import pandas as pd
import requests

sys.path.insert(0, str(Path(__file__).parents[1] / "eval"))
from gold_parser import norm  # noqa: E402

COL_Q = "Промт (вопрос)"

SYS_PROMPT = (
    "Ты помогаешь составлять тестовый набор запросов к градостроительной ГИС "
    "на русском языке. Тебе дают исходный запрос пользователя. Верни РОВНО {n} "
    "перефразировок этого запроса, по одной на строку, без нумерации и "
    "пояснений. Правила: сохрани СМЫСЛ, числовое расстояние (например «200 "
    "метров»), типы объектов И пространственное отношение без изменений. НЕ "
    "инвертируй смысл: «в радиусе / в пределах / ближе» нельзя заменять на «за "
    "пределами / вне / дальше». Меняй только формулировку, стиль и порядок слов; "
    "допускаются разговорные и формальные варианты. Не добавляй новых условий."
)


def _distance_tokens(q: str) -> set[str]:
    return set(re.findall(r"\d+\s*(?:м|метр\w*|км)", norm(q)))


def _nouns(q: str) -> set[str]:
    # crude content-word signature: russian words >=5 chars, excluding stopwords
    stop = {"покажи", "которые", "радиусе", "метров", "метра", "потому",
            "чтобы", "какие", "около", "рядом", "находятся", "расстоянии"}
    return {w for w in re.findall(r"[а-яё]{5,}", norm(q)) if w not in stop}


def generate(host: str, model: str, question: str, n: int,
             temperature: float, timeout: float) -> list[str]:
    prompt = SYS_PROMPT.format(n=n) + f"\n\nИсходный запрос:\n{question}"
    r = requests.post(
        f"{host}/api/generate",
        json={"model": model, "prompt": prompt, "stream": False,
              # keep the model resident between calls — on a shared server the
              # model is otherwise evicted and reloaded per request (minutes).
              "keep_alive": "15m",
              "options": {"temperature": temperature}},
        timeout=timeout,
    )
    r.raise_for_status()
    text = r.json().get("response", "")
    lines = [re.sub(r"^\s*\d+[.)]\s*", "", ln).strip(" -–—\t")
             for ln in text.splitlines() if ln.strip()]
    return [ln for ln in lines if len(ln) > 10]


# spatial-polarity inversions: a "within radius" query must not be paraphrased
# into an "outside/beyond radius" one (distance token survives but meaning flips).
_INVERSION = re.compile(
    r"за предел|вне\b|снаружи|дальше|за границ|более чем|не ближе|"
    r"превыша\w* \d|больше \d|дальше чем"
)


def valid(base: str, cand: str) -> bool:
    if norm(cand) == norm(base):
        return False
    if _distance_tokens(base) and _distance_tokens(cand) != _distance_tokens(base):
        return False
    # spatial polarity must match: reject an inversion the base did not have
    nb, nc = norm(base), norm(cand)
    if _INVERSION.search(nc) and not _INVERSION.search(nb):
        return False
    # at least one base content noun must survive (guards against total topic
    # drift while still allowing synonym paraphrases like магазины→супермаркеты;
    # the distance + polarity guards protect the meaning-critical parts).
    bn = _nouns(base)
    if bn and not (bn & _nouns(cand)):
        return False
    return True


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--ollama-host", default="http://a.dgx:11434")
    # small models stay resident on the shared server; gpt-oss:20b was evicted
    # and reloaded per call (minutes). qwen2.5:7b-instruct paraphrases fine.
    ap.add_argument("--model", default="qwen2.5:7b-instruct")
    ap.add_argument("--base", default="benchmarks/data/gold/exp_data.csv")
    ap.add_argument("--n-paraphrases", type=int, default=10)
    ap.add_argument("--temperature", type=float, default=0.9)
    ap.add_argument("--timeout", type=float, default=120.0)
    ap.add_argument("--attempts", type=int, default=3)
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--out", default="benchmarks/data/gold/expanded.csv")
    args = ap.parse_args()

    df = pd.read_csv(args.base, sep=";", engine="python")
    df = df[df[COL_Q].notna()].reset_index(drop=True)
    if args.limit:
        df = df.head(args.limit)

    # incremental, resumable: one JSONL row per output query, appended as we go
    jsonl_path = Path(args.out).with_suffix(".jsonl")
    done_bases: set[int] = set()
    if jsonl_path.exists():
        for line in jsonl_path.open(encoding="utf-8"):
            try:
                done_bases.add(int(json.loads(line)["base_index"]))
            except Exception:  # noqa: BLE001
                pass
        print(f"resuming: {len(done_bases)} base records already done", flush=True)
    jf = jsonl_path.open("a", encoding="utf-8")

    def emit(rec: dict) -> None:
        jf.write(json.dumps(rec, ensure_ascii=False) + "\n")
        jf.flush()

    for i, row in df.iterrows():
        if i in done_bases:
            continue
        base_q = str(row[COL_Q])
        base = row.to_dict()
        base["base_index"] = i
        base["variant"] = 0
        emit(base)

        kept: list[str] = []
        attempts = 0
        while len(kept) < args.n_paraphrases and attempts < args.attempts:
            attempts += 1
            need = args.n_paraphrases - len(kept)
            try:
                cands = generate(args.ollama_host, args.model, base_q,
                                 need + 2, args.temperature, args.timeout)
            except Exception as e:
                print(f"  [{i}] generation error: {e}")
                break
            for c in cands:
                if len(kept) >= args.n_paraphrases:
                    break
                if valid(base_q, c) and norm(c) not in {norm(k) for k in kept}:
                    kept.append(c)
        for v, para in enumerate(kept, start=1):
            r = row.to_dict()
            r[COL_Q] = para
            r["base_index"] = i
            r["variant"] = v
            emit(r)
        print(f"  [{i+1}/{len(df)}] sid={row.get('scenario_id')} "
              f"kept {len(kept)}/{args.n_paraphrases}", flush=True)

    jf.close()
    # assemble the CSV from the (complete or resumed) JSONL
    out = pd.DataFrame([json.loads(l) for l in jsonl_path.open(encoding="utf-8")])
    out.to_csv(args.out, sep=";", index=False)
    print(f"\nwrote {args.out}: {len(out)} rows "
          f"({out['base_index'].nunique()} base records)", flush=True)


if __name__ == "__main__":
    main()
