def provision(*ids):
    return [
        {"scenario_id": sid, "service": service, "values": list(values), "layers": True}
        for sid in ids
        for service, values in zip(("Школа", "Детский сад"), EXPECTED[sid])
    ]


def layers(sid):
    return [
        {"scenario_id": sid, "domain": "physical_object", "type_id": i} for i in (4, 8)
    ]


def contract(ids, compliance=(), source_ids=(), comparisons=(), zones=()):
    population = {
        91001: 12000,
        91002: 4500,
        91003: 25000,
        91004: 25000,
        91005: 12000,
        91006: 12000,
        91007: 8000,
        91008: 8000,
        91009: 8000,
    }
    return {
        "provision": provision(*ids),
        "source_layers": [layer for sid in source_ids for layer in layers(sid)],
        "compliance": [{"scenario_id": sid, "violations": n} for sid, n in compliance],
        "sources": bool(compliance),
        "buffers": [sid for sid, _ in compliance],
        "population": [{"scenario_id": sid, "value": population[sid]} for sid in ids],
        "comparisons": [
            {"before": before, "after": after, "service": service}
            for before, after in comparisons
            for service in ("Школа", "Детский сад")
        ],
        "zones": list(zones),
    }


